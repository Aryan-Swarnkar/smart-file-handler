"""audit_log — append-only event trail.

Append-only BY CONSTRUCTION: no update or delete code path exists anywhere
for this table (audit_service is the sole writer, Phase 8+). BigInteger
Identity PK: sequential log inserts need no UUID randomness.
"""

from __future__ import annotations

import uuid
from typing import Any

from sqlalchemy import BigInteger, ForeignKey, Identity, Index, String
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, CreatedAtMixin


class AuditLog(Base, CreatedAtMixin):
    __tablename__ = "audit_log"
    __table_args__ = (
        # "What did this account do" timeline (Phase 11/10 views).
        Index("ix_audit_log_actor_created", "actor_id", "created_at"),
    )

    id: Mapped[int] = mapped_column(
        # GENERATED BY DEFAULT AS IDENTITY (matches the migration exactly;
        # alembic check compares identity configuration).
        BigInteger, Identity(), primary_key=True
    )
    # SET NULL: the log survives account deletion (actor becomes unknown)
    # instead of vanishing with it — audit rows outlive their subjects.
    actor_id: Mapped[uuid.UUID | None] = mapped_column(
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )
    # Dot-namespaced verb, e.g. "auth.login", "share.link_created",
    # "file.purged" — stable, greppable, extended by later phases.
    action: Mapped[str] = mapped_column(String(50), nullable=False)
    # Free-form context (target ids, ip, result) — schema evolves per action.
    details: Mapped[dict[str, Any]] = mapped_column(
        JSONB, nullable=False, default=dict
    )
