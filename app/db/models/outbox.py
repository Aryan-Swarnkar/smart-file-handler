"""outbox — the ONLY bridge from DB state to Celery.

The API inserts outbox rows in the SAME transaction as the state change they
announce; the relay (Phase 6) claims unpublished rows with SELECT ... FOR
UPDATE SKIP LOCKED, sends them to Celery, then stamps published_at.
At-least-once delivery: consumers must be idempotent (state-machine jobs use
conditional UPDATE ... WHERE status IN (...)).
"""

from __future__ import annotations

from datetime import datetime
from typing import Any

from sqlalchemy import (
    BigInteger,
    DateTime,
    Identity,
    Index,
    Integer,
    String,
    text,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base, CreatedAtMixin


class Outbox(Base, CreatedAtMixin):
    __tablename__ = "outbox"
    __table_args__ = (
        # Relay's claim query: oldest unpublished first. Partial — published
        # rows are dead weight and must never touch this index.
        Index(
            "ix_outbox_unpublished",
            "created_at",
            postgresql_where=text("published_at IS NULL"),
        ),
    )

    id: Mapped[int] = mapped_column(
        # GENERATED BY DEFAULT AS IDENTITY (matches the migration exactly).
        BigInteger, Identity(), primary_key=True
    )
    # Dot-namespaced event, e.g. "file.uploaded", "storage.delete",
    # "folder.purge" — the relay maps event_type -> Celery task.
    event_type: Mapped[str] = mapped_column(String(50), nullable=False)
    # The full message for the consumer (ids, trace context — Phase 5 puts
    # trace ids in here so one trace spans upload -> relay -> worker).
    payload: Mapped[dict[str, Any]] = mapped_column(JSONB, nullable=False)
    attempts: Mapped[int] = mapped_column(
        Integer, nullable=False, default=0
    )  # relay increments on every send attempt
    published_at: Mapped[datetime | None] = mapped_column(
        DateTime(timezone=True), nullable=True
    )
